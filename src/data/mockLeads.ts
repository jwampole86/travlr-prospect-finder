export type RegulationStatus = 'Allowed' | 'Restricted' | 'Prohibited' | 'Unknown';
export type LeadStage =
  | 'New Lead' |'Contacted' |'Interested' |'Proposal Sent' |'Under Contract' |'Live' |'Not a Fit';
export type LeadSource =
  | 'Zillow' |'Craigslist' |'Facebook Marketplace' |'Realtor.com' |'Direct' |'Referral' |'LoopNet' |'HotPads' |'Apartments.com' |'Trulia' |'Redfin' |'MLS' |'Airbnb' |'VRBO' |'Other';

export interface Lead {
  id: string;
  address: string;
  city: string;
  state: string;
  zip: string;
  lat: number;
  lng: number;
  beds: number;
  baths: number;
  price: number;
  priceType: 'sale' | 'rent';
  source: LeadSource;
  stage: LeadStage;
  regulationStatus: RegulationStatus;
  prospectScore: number;
  daysOnMarket: number;
  lastChecked: string;
  listingUrl: string;
  notes: string;
  contactName?: string;
  contactPhone?: string;
  contactEmail?: string;
  tags: string[];
  estimatedADR: number;
  estimatedOccupancy: number;
  estimatedGrossMonthly: number;
  estimatedNetMonthly: number;
  photos: string[];
  createdAt: string;
  updatedAt: string;
  // Data quality flags
  isSynthetic?: boolean;
  // Address validation flags
  addrValidated?: boolean;
  addrMismatch?: boolean;
  // Contact gating: contact info only visible after homeowner consent
  contactInfoRequested?: boolean;
  contactInfoRequestedAt?: string;
  // Property verification fields
  verificationStatus?: string;
  verificationScore?: number;
  verificationMethod?: string;
  verificationTimestamp?: string;
  verifiedAddress?: string;
  normalizedAddress?: string;
  apn?: string;
  propertyProvider?: string;
  providerPropertyId?: string;
  county?: string;
  verificationNotes?: string;
}

